import { createHash } from "node:crypto";
import type { GithubIssueClosureSnapshot } from "@wollipog/protocol";
import { isTerminal } from "@wollipog/protocol";
import type { ControlPlaneDb } from "./db.js";

const bounded = (value: unknown, max: number): value is string => typeof value === "string" &&
  value.length > 0 && value.length <= max && !value.includes("\0");
const sha = (value: unknown): value is string => typeof value === "string" && /^[0-9a-f]{64}$/u.test(value);
const record = (value: unknown): value is Record<string, unknown> => Boolean(value) && typeof value === "object" && !Array.isArray(value);

/** Canonical, bounded snapshot used for hashing and recovery. Inputs are generated by the server,
 * not accepted as a way for an agent to assert current GitHub or child evidence. */
export function normalizeIssueClosureSnapshot(value: Record<string, unknown>): GithubIssueClosureSnapshot | null {
  if (!bounded(value.repository, 256) || !/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/u.test(value.repository) ||
      !Number.isSafeInteger(value.issue) || (value.issue as number) < 1 ||
      !bounded(value.title, 1024) || value.url !== `https://github.com/${value.repository}/issues/${value.issue}` ||
      !sha(value.forgeDigest) || !["completed", "not_planned"].includes(value.reason as string) ||
      !bounded(value.explanation, 4000) || !Array.isArray(value.evidence) || value.evidence.length < 1 ||
      value.evidence.length > 32 || value.evidence.some((item) => !bounded(item, 4000)) ||
      (value.comment !== undefined && !bounded(value.comment, 65_536)) ||
      !Array.isArray(value.openPullRequests) || value.openPullRequests.length > 100 ||
      !Array.isArray(value.activeChildren) || value.activeChildren.length > 100) return null;
  const openPullRequests: GithubIssueClosureSnapshot["openPullRequests"] = [];
  for (const pr of value.openPullRequests) {
    if (!record(pr) || !Number.isSafeInteger(pr.number) || (pr.number as number) < 1 ||
        !bounded(pr.title, 1024) || pr.url !== `https://github.com/${value.repository}/pull/${pr.number}` ||
        typeof pr.headSha !== "string" || !/^[0-9a-f]{40}$/u.test(pr.headSha)) return null;
    openPullRequests.push({ number: pr.number as number, title: pr.title, url: pr.url as string, headSha: pr.headSha });
  }
  const activeChildren: GithubIssueClosureSnapshot["activeChildren"] = [];
  for (const child of value.activeChildren) {
    if (!record(child) || !bounded(child.sessionId, 256) || !bounded(child.title, 1024) || !sha(child.assignmentDigest)) return null;
    activeChildren.push({ sessionId: child.sessionId, title: child.title, assignmentDigest: child.assignmentDigest });
  }
  if (value.scopeRevision !== undefined && (!Number.isSafeInteger(value.scopeRevision) || (value.scopeRevision as number) < 1)) return null;
  return { ...(value.scopeRevision === undefined ? {} : { scopeRevision: value.scopeRevision as number }), category: "issue_closure", repository: value.repository, issue: value.issue as number,
    title: value.title, url: value.url as string, forgeDigest: value.forgeDigest,
    reason: value.reason as GithubIssueClosureSnapshot["reason"], explanation: value.explanation,
    evidence: [...value.evidence] as string[], ...(value.comment === undefined ? {} : { comment: value.comment as string }),
    openPullRequests, activeChildren };
}

/** Text containing the issue number as a standalone number, in any phrasing (`#123`, `issues 122 and
 * 123`, `.../issues/123`). Matching the bare number over-includes on purpose: a match only ever
 * adds a child, and prose can show a task bears on an issue but never that it does not. */
const mentionsIssue = (text: string | null | undefined, issue: number) =>
  typeof text === "string" && new RegExp(`(?<!\\d)${issue}(?!\\d)`, "u").test(text);

/** Live campaign children whose work can bear on the issue (#3084). A child is left out only when
 * the campaign work ledger attributes it elsewhere: its open attempt is on an item outside the
 * issue's lineage, no attempt of it was ever in that lineage, its launch assignment is recorded,
 * and no prompt in its history or queue names the issue. Every other child stays included
 * conservatively: a task can move between issues in steering history, and a later "continue" prompt
 * is not proof it is unrelated. A change to the ledger that moves a child in or out of this set
 * still changes the digest. Without an issue, as for a campaign scope change, every live child is
 * included. */
export function issueClosureActiveChildren(db: ControlPlaneDb, sessionId: string, issue?: { repository: string; number: number }) {
  const attribution = issue ? db.campaignWorkLedger.issueLineageSessions(sessionId, issue.repository, issue.number) : null;
  return db.campaignDescendantIds(sessionId).flatMap((id) => {
    const child = db.getSession(id);
    if (!child || isTerminal(child.status) || child.archived) return [];
    const assignment = db.initialUserMessageText(id);
    const state = db.issueClosureAssignmentState(id);
    const prompts = [...(child.queued ?? []), ...(child.pendingPrompts ?? [])];
    // The runner echoes the launch prompt as the first user message; until then it is unknown.
    if (issue && attribution?.elsewhere.has(id) && !attribution.lineage.has(id) && assignment !== null &&
        ![...db.issueClosurePromptTexts(id, String(issue.number)), ...prompts.map((prompt) => prompt.text)]
          .some((text) => mentionsIssue(text, issue.number))) return [];
    return [{ sessionId: id, title: child.title,
      assignmentDigest: createHash("sha256").update(JSON.stringify({
        assignment, state, prompts, parentSessionId: child.parentSessionId, worktreePath: child.worktreePath,
        pending: db.unconsumedWorkflowDecisionsForSession(id).map((decision) => ({
          occurrenceId: decision.occurrenceId, digest: decision.resourceDigest, status: decision.status,
        })),
      })).digest("hex") }];
  });
}
