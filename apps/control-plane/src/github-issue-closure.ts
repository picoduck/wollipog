import { createHash } from "node:crypto";
import type { GithubIssueClosureSnapshot, SessionView } from "@wollipog/protocol";
import { campaignIssueForgeUrl, campaignRepositoryLocation, isTerminal, validIssueAdmission } from "@wollipog/protocol";
import type { ControlPlaneDb } from "./db.js";

const bounded = (value: unknown, max: number): value is string => typeof value === "string" &&
  value.length > 0 && value.length <= max && !value.includes("\0");
const sha = (value: unknown): value is string => typeof value === "string" && /^[0-9a-f]{64}$/u.test(value);
const record = (value: unknown): value is Record<string, unknown> => Boolean(value) && typeof value === "object" && !Array.isArray(value);

/** Canonical, bounded snapshot used for hashing and recovery. Inputs are generated by the server,
 * not accepted as a way for an agent to assert current forge or child evidence. */
export function normalizeIssueClosureSnapshot(value: Record<string, unknown>): GithubIssueClosureSnapshot | null {
  if (!validIssueAdmission(value.issueAdmission) || value.dispositionRecommendationId !== undefined && !bounded(value.dispositionRecommendationId, 256)) return null;
  if (value.delivery !== undefined && (!Array.isArray(value.delivery) || value.delivery.length > 100 || value.delivery.some((p) =>
      !record(p) || !Number.isSafeInteger(p.number) || (p.number as number) < 1 || typeof p.headSha !== "string" || !/^[0-9a-f]{40}$/u.test(p.headSha) ||
      typeof p.mergeCommitSha !== "string" || !/^[0-9a-f]{40}$/u.test(p.mergeCommitSha)))) return null;
  // A github.com `owner/name`, or a host-qualified GitLab project (#3539) whose issue address is
  // `http(s)://<host>/<project>/-/issues/<n>`.
  if (!bounded(value.repository, 256) || !campaignRepositoryLocation(value.repository) ||
      !Number.isSafeInteger(value.issue) || (value.issue as number) < 1 ||
      !bounded(value.title, 1024) || !campaignIssueForgeUrl(value.url, value.repository, "issue", value.issue as number) ||
      !sha(value.forgeDigest) || !["completed", "not_planned"].includes(value.reason as string) ||
      !bounded(value.explanation, 4000) || !Array.isArray(value.evidence) || value.evidence.length < 1 ||
      value.evidence.length > 32 || value.evidence.some((item) => !bounded(item, 4000)) ||
      (value.comment !== undefined && !bounded(value.comment, 65_536)) ||
      !Array.isArray(value.openPullRequests) || value.openPullRequests.length > 100 ||
      !Array.isArray(value.activeChildren) || value.activeChildren.length > 100) return null;
  const openPullRequests: GithubIssueClosureSnapshot["openPullRequests"] = [];
  for (const pr of value.openPullRequests) {
    if (!record(pr) || !Number.isSafeInteger(pr.number) || (pr.number as number) < 1 ||
        !bounded(pr.title, 1024) || !campaignIssueForgeUrl(pr.url, value.repository, "change", pr.number as number) ||
        typeof pr.headSha !== "string" || !/^[0-9a-f]{40}$/u.test(pr.headSha)) return null;
    openPullRequests.push({ number: pr.number as number, title: pr.title, url: pr.url as string, headSha: pr.headSha });
  }
  const activeChildren: GithubIssueClosureSnapshot["activeChildren"] = [];
  for (const child of value.activeChildren) {
    if (!record(child) || !bounded(child.sessionId, 256) || !bounded(child.title, 1024) || !sha(child.assignmentDigest)) return null;
    activeChildren.push({ sessionId: child.sessionId, title: child.title, assignmentDigest: child.assignmentDigest });
  }
  if (value.scopeRevision !== undefined && (!Number.isSafeInteger(value.scopeRevision) || (value.scopeRevision as number) < 1)) return null;
  return { ...(value.scopeRevision === undefined ? {} : { scopeRevision: value.scopeRevision as number }), category: "issue_closure", repository: value.repository, issue: value.issue as number,
    title: value.title, url: value.url as string, forgeDigest: value.forgeDigest,
    reason: value.reason as GithubIssueClosureSnapshot["reason"], explanation: value.explanation,
    evidence: [...value.evidence] as string[], ...(value.comment === undefined ? {} : { comment: value.comment as string }),
    openPullRequests, activeChildren,
    ...(value.delivery === undefined ? {} : { delivery: structuredClone(value.delivery) as GithubIssueClosureSnapshot["delivery"] }),
    ...(value.dispositionRecommendationId === undefined ? {} : { dispositionRecommendationId: value.dispositionRecommendationId as string }),
    ...(value.issueAdmission === undefined ? {} : { issueAdmission: structuredClone(value.issueAdmission) as GithubIssueClosureSnapshot["issueAdmission"] }) };
}

/** A child's outstanding prompts by identity and content only (#3793). Both projections decode the
 * durable prompt commands, keyed by command id, whose payload is never rewritten: it is only
 * cleared, which drops the prompt from both, so a command id fixes its content. Delivery bookkeeping
 * (state, attempt count, revision, timestamps, errors) moves on every outbox retry and receipt, so
 * binding it would let a routine retry of an already-pending prompt revoke an approval. A new
 * prompt, or one leaving the projection, still changes the list. With no prompts the list is
 * empty, as before, so such a child's digest is unchanged from earlier releases. */
function issueClosurePrompts(child: Pick<SessionView, "queued" | "pendingPrompts">) {
  const prompts = new Map<string, { commandId: string; text: string; hasImages: boolean }>();
  for (const { commandId, text, hasImages } of child.pendingPrompts ?? []) prompts.set(commandId, { commandId, text, hasImages: hasImages === true });
  for (const { id, text, hasImages } of child.queued ?? []) {
    if (!prompts.has(id)) prompts.set(id, { commandId: id, text, hasImages: hasImages === true });
  }
  return [...prompts.values()];
}

/** Live campaign children whose work can bear on the issue (#3084). A child is left out only when
 * its launch prompt is recorded (the runner echoes it as the first user message) and the campaign
 * work ledger attributes it elsewhere: it has an open attempt, and every attempt it has ever had is
 * on an item that has never tracked the issue and has no follow-up links. Every other child stays
 * included: a task can move between issues in steering history, and a later "continue" prompt is
 * not proof it is unrelated. Exclusion is decided from append-only history, so a child once
 * connected to the issue is never excluded again, and bringing one into the set changes the
 * digest. Without an issue, as for a campaign scope change, every live child is included. */
export function issueClosureActiveChildren(db: ControlPlaneDb, sessionId: string, issue?: { repository: string; number: number }) {
  const excludable = issue ? db.campaignWorkLedger.issueClosureExcludableSessions(sessionId, issue.repository, issue.number) : null;
  return db.campaignDescendantIds(sessionId).flatMap((id) => {
    const child = db.getSession(id);
    if (!child || isTerminal(child.status) || child.archived) return [];
    const assignment = db.initialUserMessageText(id);
    if (excludable?.has(id) && assignment !== null) return [];
    const state = db.issueClosureAssignmentState(id);
    return [{ sessionId: id, title: child.title,
      assignmentDigest: createHash("sha256").update(JSON.stringify({
        assignment, state, prompts: issueClosurePrompts(child), parentSessionId: child.parentSessionId, worktreePath: child.worktreePath,
        pending: db.unconsumedWorkflowDecisionsForSession(id).map((decision) => ({
          occurrenceId: decision.occurrenceId, digest: decision.resourceDigest, status: decision.status,
        })),
      })).digest("hex") }];
  });
}
