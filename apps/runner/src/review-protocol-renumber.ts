/** Static, deliberately narrow protocol declaration reader. Never execute PR code. */
export const LEDGER = "packages/protocol/src/protocol-version.ts";
const OPEN = "const PROTOCOL_VERSION_HISTORY: readonly number[] = [\n";
const CLOSE = "];\n\nexport const PROTOCOL_VERSION: number = Math.max(...PROTOCOL_VERSION_HISTORY);\n";

export function ledgerEntries(text: string): { prefix: string; entries: Map<number, string>; slots: string } | null {
  if (Buffer.byteLength(text) > 2 * 1024 * 1024) return null;
  const at = text.indexOf(OPEN);
  if (at < 0 || !text.endsWith(CLOSE)) return null;
  // Outside the declaration only a leading documentation comment is supported.
  const prefix = text.slice(0, at);
  if (!/^\/\*\*[^]*?\*\/\n$/u.test(prefix) || prefix.slice(3, -3).includes("*/")) return null;
  const body = text.slice(at + OPEN.length, -CLOSE.length);
  const slots = [...body.matchAll(/^  \/\/ v\d+ slot\n/gmu)].map((m) => m[0]).join("");
  const withoutSlots = body.replace(/^  \/\/ v\d+ slot\n/gmu, "");
  const entries = new Map<number, string>();
  let consumed = "";
  let previous = 0;
  for (const match of withoutSlots.matchAll(/  \/\/ (\d+):[^\n]*\n(?:  \/\/[^\n]*\n)*  (\d+),\n/gu)) {
    const version = Number(match[1]);
    if (match[1] !== match[2] || !Number.isSafeInteger(version) || version <= previous) return null;
    entries.set(version, match[0]);
    previous = version;
    consumed += match[0];
  }
  return consumed === withoutSlots && entries.size ? { prefix, entries, slots } : null;
}

export function replaceVersion(text: string, oldVersion: number, newVersion: number): string {
  return text.replace(new RegExp(`(?<![0-9])${oldVersion}(?![0-9])`, "gu"), String(newVersion));
}

/** A ledger renumber moves exactly one entry; anchors and all other bytes remain unchanged. */
export function renumberedLedger(before: string, after: string, oldVersion: number, newVersion: number): boolean {
  const a = ledgerEntries(before), b = ledgerEntries(after);
  if (!a || !b || a.prefix !== b.prefix || a.slots !== b.slots || a.entries.size !== b.entries.size ||
      !a.entries.has(oldVersion) || a.entries.has(newVersion) || b.entries.has(oldVersion) ||
      replaceVersion(a.entries.get(oldVersion)!, oldVersion, newVersion) !== b.entries.get(newVersion)) return false;
  return [...a.entries].every(([version, entry]) => version === oldVersion || b.entries.get(version) === entry);
}

/** The ledger's own diff ignores entries that arrived from the base, never edits to those entries. */
export function ledgerDelta(base: string, head: string, oldVersion: number, newVersion: number): string | null {
  const a = ledgerEntries(base), b = ledgerEntries(head);
  if (!a || !b || a.prefix !== b.prefix || a.slots !== b.slots) return null;
  const changes: string[] = [];
  for (const version of new Set([...a.entries.keys(), ...b.entries.keys()])) {
    if (a.entries.get(version) === b.entries.get(version)) continue;
    for (const [sign, entry] of [["-", a.entries.get(version)], ["+", b.entries.get(version)]] as const) {
      if (entry) changes.push(sign + replaceVersion(entry, oldVersion, newVersion));
    }
  }
  return JSON.stringify(changes.sort());
}

/** Generated output needs reproduction, not a text substitution. Unsupported generators fail closed. */
export function generated(path: string, text: string): boolean {
  return /generated|(?:^|\/)dist\//iu.test(path) || /(?:@generated|auto[- ]generated|generated by|do not edit)/iu.test(text);
}
