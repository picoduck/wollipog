import type { BaseMergeGit } from "./review-base-merge.js";

export const BUILT_IN_SKILLS = "apps/control-plane/src/built-in-skills.generated.ts";

/** Trusted renderer, not the PR's generator. Unsupported binary sources fail closed. */
export async function reproduceBuiltInSkills(git: BaseMergeGit, tree: string): Promise<string | null> {
  const paths = (await git(["ls-tree", "-r", "-z", tree, "--", "skills/"])).split("\0").filter(Boolean);
  if (paths.length > 256) return null;
  const skills = new Map<string, Array<{ path: string; content: string }>>();
  let bytes = 0;
  for (const record of paths) {
    // The shipped collector ignores top-level files and hidden entries.
    if (/^[0-9]{6} \S+ [0-9a-f]{40}\tskills\/[^/]+$/u.test(record)) continue;
    const match = /^100644 blob [0-9a-f]{40}\tskills\/([^/]+)\/(.+)$/u.exec(record);
    if (!match) return null;
    const name = match[1]!, path = match[2]!;
    if ([name, ...path.split("/")].some((part) => part.startsWith("."))) continue;
    const content = await git(["cat-file", "blob", `${tree}:skills/${name}/${path}`]);
    bytes += Buffer.byteLength(content);
    if (bytes > 2 * 1024 * 1024 || content.includes("\0")) return null;
    const files = skills.get(name) ?? [];
    files.push({ path, content });
    skills.set(name, files);
  }
  const byCodeUnits = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
  const entries = [...skills].sort(([a], [b]) => byCodeUnits(a, b)).filter(([, files]) => files.some((f) => f.path === "SKILL.md"))
    .map(([name, files]) => [
      "  {", `    name: ${JSON.stringify(name)},`, "    files: [",
      ...files.sort((a, b) => byCodeUnits(a.path, b.path)).map((file) => [
        "      {", `        path: ${JSON.stringify(file.path)},`, '        encoding: "utf8",',
        `        content: [\n${file.content.split("\n").map((line) => `          ${JSON.stringify(line)},`).join("\n")}\n        ].join("\\n"),`,
        "      },",
      ].join("\n")), "    ],", "  },",
    ].join("\n"));
  return [
    "// Generated by scripts/generate-built-in-skills.mjs from the repository's skills/ directory.",
    "// Do not edit: change skills/ and run `pnpm generate:built-in-skills`.",
    'import type { SkillFile } from "@wollipog/protocol";', "", "export interface BuiltInSkillSource {",
    "  name: string;", "  files: SkillFile[];", "}", "",
    "export const BUILT_IN_SKILL_SOURCES: readonly BuiltInSkillSource[] = [", ...entries, "];", "",
  ].join("\n");
}
