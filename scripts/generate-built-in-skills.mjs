/**
 * Compile the repository's top-level `skills/` directory into
 * `apps/control-plane/src/built-in-skills.generated.ts`, so every release carries the exact skill
 * files it was built from and the control plane can seed them as built-in Skill Library entries.
 *
 * Run `pnpm generate:built-in-skills` in the same commit that changes `skills/`. The unit test
 * `generate-built-in-skills.test.mjs` fails while the checked-in module and the directory differ.
 */
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const SKILLS_DIR = fileURLToPath(new URL("../skills", import.meta.url));
export const GENERATED_MODULE = fileURLToPath(
  new URL("../apps/control-plane/src/built-in-skills.generated.ts", import.meta.url),
);

/** Code-unit order, the same order the version digest's manifest uses. */
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function isText(bytes) {
  if (bytes.includes(0)) return false;
  try {
    return Buffer.from(new TextDecoder("utf-8", { fatal: true }).decode(bytes), "utf8").equals(bytes);
  } catch {
    return false;
  }
}

function collectFiles(root, relative, files) {
  for (const entry of readdirSync(join(root, relative)).sort(byCodeUnits)) {
    // Hidden entries (.DS_Store, editor swap files) are never part of a shipped skill.
    if (entry.startsWith(".")) continue;
    const path = relative ? `${relative}/${entry}` : entry;
    const stat = lstatSync(join(root, path));
    if (stat.isDirectory()) {
      collectFiles(root, path, files);
    } else if (stat.isFile()) {
      const bytes = readFileSync(join(root, path));
      files.push(isText(bytes)
        ? { path, encoding: "utf8", content: bytes.toString("utf8") }
        : { path, encoding: "base64", content: bytes.toString("base64") });
    } else {
      throw new Error(`skills/${path} is not a regular file or directory; built-in skills cannot contain links`);
    }
  }
}

/** Every directory of `skillsDir` that holds a SKILL.md is one built-in skill named after it. */
export function collectBuiltInSkills(skillsDir = SKILLS_DIR) {
  const skills = [];
  for (const name of readdirSync(skillsDir).sort(byCodeUnits)) {
    if (name.startsWith(".")) continue;
    const stat = lstatSync(join(skillsDir, name));
    if (!stat.isDirectory()) continue;
    const files = [];
    collectFiles(join(skillsDir, name), "", files);
    if (!files.some((file) => file.path === "SKILL.md")) continue;
    files.sort((a, b) => byCodeUnits(a.path, b.path));
    skills.push({ name, files });
  }
  return skills;
}

/** Text files are emitted line by line, so a change to a skill reviews as a readable diff here. */
function renderContent(file) {
  if (file.encoding !== "utf8") return JSON.stringify(file.content);
  const lines = file.content.split("\n");
  return `[\n${lines.map((line) => `          ${JSON.stringify(line)},`).join("\n")}\n        ].join("\\n")`;
}

export function renderBuiltInSkillsModule(skills) {
  const entries = skills.map((skill) => [
    "  {",
    `    name: ${JSON.stringify(skill.name)},`,
    "    files: [",
    ...skill.files.map((file) => [
      "      {",
      `        path: ${JSON.stringify(file.path)},`,
      `        encoding: ${JSON.stringify(file.encoding)},`,
      `        content: ${renderContent(file)},`,
      "      },",
    ].join("\n")),
    "    ],",
    "  },",
  ].join("\n"));
  return [
    "// Generated by scripts/generate-built-in-skills.mjs from the repository's skills/ directory.",
    "// Do not edit: change skills/ and run `pnpm generate:built-in-skills`.",
    "import type { SkillFile } from \"@wollipog/protocol\";",
    "",
    "export interface BuiltInSkillSource {",
    "  name: string;",
    "  files: SkillFile[];",
    "}",
    "",
    "export const BUILT_IN_SKILL_SOURCES: readonly BuiltInSkillSource[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GENERATED_MODULE, renderBuiltInSkillsModule(collectBuiltInSkills()));
  console.log(`wrote ${GENERATED_MODULE}`);
}
